package org.vernac.compiler.generator;

import com.palantir.javapoet.*;
import java.util.*;
import javax.lang.model.element.Modifier;
import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;
import org.vernac.compiler.ast.*;
import org.vernac.compiler.dto.ResolvedSchema;
import org.vernac.runtime.ports.PatchField;
import static org.vernac.compiler.dto.ResolvedSchema.*;

/** Generates immutable transport records with explicitly scoped strict Jackson codecs. */
public final class DtoGenerator {
    private static final ClassName JSON = ClassName.get("org.vernac.runtime.json","JsonValues");
    private static final ClassName NODE = ClassName.get("com.fasterxml.jackson.databind","JsonNode");
    private static final ClassName OBJECT = ClassName.get("com.fasterxml.jackson.databind.node","ObjectNode");
    private static ClassName jackson(String name) { return ClassName.get("com.fasterxml.jackson.databind",name); }

    public JavaFile generate(OutboundAdapterNode adapter, CompilationUnitNode unit, List<ResolvedSchema> schemas) {
        return generate(adapter.name(), unit.namespace() + ".adapter.outbound.dto", schemas);
    }
    public JavaFile generate(String adapterName, String dtoPackage, List<ResolvedSchema> schemas) {
        ClassName holder=ClassName.get(dtoPackage,adapterName+"Dtos");
        var builder=TypeSpec.classBuilder(holder).addModifiers(Modifier.PUBLIC,Modifier.FINAL).addAnnotation(NullMarked.class)
                .addJavadoc("Adapter-local transport DTOs. Generated by Vernac; do not edit.\n")
                .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
        for(var schema:schemas) {
            builder.addType(record(schema,holder));
            builder.addType(reader(schema,holder));
            builder.addType(writer(schema,holder));
        }
        return JavaFile.builder(holder.packageName(),builder.build()).indent("    ").skipJavaLangImports(true).build();
    }
    private TypeSpec record(ResolvedSchema schema,ClassName holder) {
        ClassName own=holder.nestedClass(schema.source().name());
        var ctor=MethodSpec.constructorBuilder().addModifiers(Modifier.PUBLIC);
        var factory=MethodSpec.methodBuilder("of").addModifiers(Modifier.PUBLIC,Modifier.STATIC).returns(own);
        List<CodeBlock> args=new ArrayList<>();
        for(var field:schema.fields()) {
            var f=field.source();TypeName raw=raw(field.shape(),holder),component=raw;
            CodeBlock value=CodeBlock.of("$N",f.name());
            String path=schema.source().name()+"."+f.name();
            if(f.patch()) {
                component=ParameterizedTypeName.get(ClassName.get(PatchField.class),raw.box());
                value=CodeBlock.of("$T.patchContract($N, $S, $L)",JSON,f.name(),path,f.type().isOptional());
                if(field.shape() instanceof Sequence) value=CodeBlock.of("$L.map(v -> $L)",value,copy(field.shape(),CodeBlock.of("v"),path,0));
            } else if(f.type().isOptional()) {
                component=ParameterizedTypeName.get(ClassName.get(Optional.class),raw.box());
                value=CodeBlock.of("$T.require($N, $S)",JSON,f.name(),path);
                if(field.shape() instanceof Sequence) value=CodeBlock.of("$L.map(v -> $L)",value,copy(field.shape(),CodeBlock.of("v"),path,0));
            } else if(!raw.isPrimitive()) value=copy(field.shape(),value,path,0);
            ctor.addParameter(component,f.name()).addStatement("this.$N = $L",f.name(),value);
            if(f.patch()) { factory.addParameter(component,f.name());args.add(CodeBlock.of("$N",f.name())); }
            else if(f.type().isOptional()) {
                factory.addParameter(raw.box().annotated(AnnotationSpec.builder(Nullable.class).build()),f.name());
                args.add(CodeBlock.of("$T.ofNullable($N)",Optional.class,f.name()));
            } else { factory.addParameter(raw,f.name());args.add(CodeBlock.of("$N",f.name())); }
        }
        factory.addStatement("return new $T($L)",own,CodeBlock.join(args,", "));
        return TypeSpec.recordBuilder(own.simpleName()).addModifiers(Modifier.PUBLIC,Modifier.STATIC).addAnnotation(NullMarked.class)
                .addAnnotation(AnnotationSpec.builder(ClassName.get("com.fasterxml.jackson.databind.annotation","JsonDeserialize"))
                        .addMember("using","$T.class",readerName(holder,own.simpleName())).build())
                .addAnnotation(AnnotationSpec.builder(ClassName.get("com.fasterxml.jackson.databind.annotation","JsonSerialize"))
                        .addMember("using","$T.class",writerName(holder,own.simpleName())).build())
                .recordConstructor(ctor.build()).addMethod(factory.build()).build();
    }
    private CodeBlock copy(Shape shape,CodeBlock value,String path,int depth) {
        if(shape instanceof Sequence s) {
            CodeBlock list=CodeBlock.of("$T.copyList($L, $S)",JSON,value,path);
            if(s.element() instanceof Sequence) return CodeBlock.of("$L.stream().map(v$L -> $L).toList()",list,depth,
                    copy(s.element(),CodeBlock.of("v$L",depth),path+"[]",depth+1));
            return list;
        }
        return CodeBlock.of("$T.require($L, $S)",JSON,value,path);
    }
    private TypeSpec reader(ResolvedSchema schema,ClassName holder) {
        ClassName own=holder.nestedClass(schema.source().name()),reader=readerName(holder,own.simpleName());
        var read=MethodSpec.methodBuilder("read").addModifiers(Modifier.PRIVATE,Modifier.STATIC).returns(own)
                .addParameter(NODE.annotated(AnnotationSpec.builder(Nullable.class).build()),"node").addParameter(String.class,"path")
                .addStatement("var object = $T.object(node, path)",JSON);
        List<CodeBlock> args=new ArrayList<>();
        for(var field:schema.fields()) {
            CodeBlock node=CodeBlock.of("object.get($S)",field.externalName());
            CodeBlock path=CodeBlock.of("path + $S","."+field.externalName());
            if(field.source().patch()) args.add(CodeBlock.of("$T.patch($L, $L, $L, (n, p) -> $L)",JSON,node,path,field.source().type().isOptional(),decode(field.shape(),CodeBlock.of("n"),CodeBlock.of("p"),holder,0)));
            else if(field.source().type().isOptional()) args.add(CodeBlock.of("$T.optional($L, $L, (n, p) -> $L)",JSON,node,path,decode(field.shape(),CodeBlock.of("n"),CodeBlock.of("p"),holder,0)));
            else args.add(decode(field.shape(),node,path,holder,0));
        }
        read.addStatement("return $T.of($L)",own,CodeBlock.join(args,",\n"));
        var deserialize=MethodSpec.methodBuilder("deserialize").addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(own)
                .addParameter(ClassName.get("com.fasterxml.jackson.core","JsonParser"),"parser")
                .addParameter(jackson("DeserializationContext"),"context").addException(java.io.IOException.class)
                .beginControlFlow("try").addStatement("return read($T.readTree(parser), $S)",JSON,"$")
                .nextControlFlow("catch ($T ex)",ClassName.get("org.vernac.runtime.json","DtoContractException"))
                .addStatement("throw $T.from(parser, ex.getMessage(), ex)",jackson("JsonMappingException")).endControlFlow();
        var nullValue=MethodSpec.methodBuilder("getNullValue").addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(own)
                .addParameter(jackson("DeserializationContext"),"context")
                .addStatement("throw new $T($S, $S)",ClassName.get("org.vernac.runtime.json","DtoContractException"),"$","Expected JSON object");
        return TypeSpec.classBuilder(reader.simpleName()).addModifiers(Modifier.PUBLIC,Modifier.STATIC,Modifier.FINAL)
                .superclass(ParameterizedTypeName.get(jackson("JsonDeserializer"),own)).addMethod(read.build()).addMethod(deserialize.build()).addMethod(nullValue.build()).build();
    }
    private TypeSpec writer(ResolvedSchema schema,ClassName holder) {
        ClassName own=holder.nestedClass(schema.source().name());
        var write=MethodSpec.methodBuilder("write").addModifiers(Modifier.PRIVATE,Modifier.STATIC).returns(OBJECT).addParameter(own,"value")
                .addStatement("var object = $T.instance.objectNode()",ClassName.get("com.fasterxml.jackson.databind.node","JsonNodeFactory"));
        for(var field:schema.fields()) {
            CodeBlock getter=CodeBlock.of("value.$N()",field.source().name());
            if(field.source().patch()) {
                write.beginControlFlow("if ($L.isClear())",getter).addStatement("object.putNull($S)",field.externalName())
                        .nextControlFlow("else if ($L.isSet())",getter)
                        .addStatement("object.set($S, $L)",field.externalName(),encode(field.shape(),CodeBlock.of("$L.value().orElseThrow()",getter),holder,0)).endControlFlow();
            } else if(field.source().type().isOptional()) {
                write.beginControlFlow("if ($L.isPresent())",getter)
                        .addStatement("object.set($S, $L)",field.externalName(),encode(field.shape(),CodeBlock.of("$L.orElseThrow()",getter),holder,0));
                if(field.source().absentAsNull()) write.nextControlFlow("else").addStatement("object.putNull($S)",field.externalName());
                write.endControlFlow();
            } else write.addStatement("object.set($S, $L)",field.externalName(),encode(field.shape(),getter,holder,0));
        }
        write.addStatement("return object");
        var serialize=MethodSpec.methodBuilder("serialize").addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(void.class)
                .addParameter(own,"value").addParameter(ClassName.get("com.fasterxml.jackson.core","JsonGenerator"),"generator")
                .addParameter(jackson("SerializerProvider"),"provider").addException(java.io.IOException.class)
                .addStatement("generator.writeTree(write(value))");
        return TypeSpec.classBuilder(writerName(holder,own.simpleName()).simpleName()).addModifiers(Modifier.PUBLIC,Modifier.STATIC,Modifier.FINAL)
                .superclass(ParameterizedTypeName.get(jackson("JsonSerializer"),own)).addMethod(write.build()).addMethod(serialize.build()).build();
    }
    private TypeName raw(Shape shape,ClassName holder) {
        if(shape instanceof Scalar s)return TypeName.get(s.javaType());
        if(shape instanceof Nested n)return holder.nestedClass(n.schemaName());
        return ParameterizedTypeName.get(ClassName.get(List.class),raw(((Sequence)shape).element(),holder).box());
    }
    private CodeBlock decode(Shape shape,CodeBlock node,CodeBlock path,ClassName holder,int depth) {
        if(shape instanceof Scalar s)return CodeBlock.of("$T.scalar($L, $L, $T.class)",JSON,node,path,TypeName.get(s.javaType()).box());
        if(shape instanceof Nested n)return CodeBlock.of("$T.read($L, $L)",readerName(holder,n.schemaName()),node,path);
        return CodeBlock.of("$T.list($L, $L, (n$L, p$L) -> $L)",JSON,node,path,depth,depth,
                decode(((Sequence)shape).element(),CodeBlock.of("n$L",depth),CodeBlock.of("p$L",depth),holder,depth+1));
    }
    private CodeBlock encode(Shape shape,CodeBlock value,ClassName holder,int depth) {
        if(shape instanceof Scalar)return CodeBlock.of("$T.scalarNode($L)",JSON,value);
        if(shape instanceof Nested n)return CodeBlock.of("$T.write($L)",writerName(holder,n.schemaName()),value);
        return CodeBlock.of("$T.array($L, v$L -> $L)",JSON,value,depth,encode(((Sequence)shape).element(),CodeBlock.of("v$L",depth),holder,depth+1));
    }
    private ClassName readerName(ClassName holder,String name) {return holder.nestedClass("__JsonReader_"+name);}
    private ClassName writerName(ClassName holder,String name) {return holder.nestedClass("__JsonWriter_"+name);}
}
