package org.vernac.compiler.generator;

import com.palantir.javapoet.*;

import org.jspecify.annotations.NullMarked;
import org.vernac.compiler.ast.*;
import org.vernac.compiler.inbound.*;
import org.vernac.compiler.pipeline.ResolvedProject;

import java.util.*;

import javax.lang.model.element.Modifier;

/** Server-rendered boundaries built on the shared, resolved HTTP conversion plan. */
public final class InboundMvcGenerator {
    private static final ClassName VIEW =
            ClassName.get("org.springframework.web.servlet", "ModelAndView");
    private static final ClassName INPUTS =
            ClassName.get("org.vernac.runtime.http.inbound", "MvcInputs");
    private static final ClassName RESPONSES =
            ClassName.get("org.vernac.runtime.http.inbound", "MvcResponses");
    private static final ClassName ERRORS =
            ClassName.get("org.vernac.runtime.http.inbound", "InboundHttpErrors");
    private static final ClassName REQUEST =
            ClassName.get("jakarta.servlet.http", "HttpServletRequest");

    private static ClassName annotation(String name) {
        return ClassName.get("org.springframework.web.bind.annotation", name);
    }

    public List<JavaFile> generate(
            InboundHttpAdapterNode adapter,
            CompilationUnitNode unit,
            ResolvedProject project,
            ResolvedInbound plan) {
        String pkg = unit.namespace() + ".adapter.inbound.http";
        var owner = ClassName.get(pkg, adapter.name());
        var mappings = ClassName.get(pkg + ".mapping", adapter.name() + "Mappings");
        var type =
                TypeSpec.classBuilder(owner)
                        .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
                        .addAnnotation(NullMarked.class)
                        .addAnnotation(
                                ClassName.get("org.springframework.stereotype", "Controller"))
                        .addJavadoc("MVC inbound adapter generated by Vernac. Do not edit.\n");
        var constructor = MethodSpec.constructorBuilder().addModifiers(Modifier.PUBLIC);
        for (var dependency : plan.dependencies()) {
            var id = dependency.symbol().identity();
            var java = ClassName.get(id.namespace() + ".usecase", id.name());
            type.addField(java, dependency.field().name(), Modifier.PRIVATE, Modifier.FINAL);
            constructor
                    .addParameter(java, dependency.field().name())
                    .addStatement(
                            "this.$N = $T.requireNonNull($N)",
                            dependency.field().name(),
                            Objects.class,
                            dependency.field().name());
        }
        type.addMethod(constructor.build());
        for (var endpoint : plan.endpoints()) {
            type.addMethod(entry(adapter, endpoint.source()));
            type.addMethod(loader(endpoint, mappings));
        }
        type.addMethod(failure(adapter, project, pkg));
        BehaviorGenerator.addDebugFingerprint(type, file(pkg, type), unit, project);
        var advice =
                TypeSpec.classBuilder(adapter.name() + "Errors")
                        .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
                        .addAnnotation(NullMarked.class)
                        .addAnnotation(
                                AnnotationSpec.builder(
                                                ClassName.get(
                                                        "org.springframework.core.annotation",
                                                        "Order"))
                                        .addMember("value", "0")
                                        .build())
                        .addAnnotation(
                                AnnotationSpec.builder(annotation("ControllerAdvice"))
                                        .addMember("assignableTypes", "$T.class", owner)
                                        .build())
                        .addField(owner, "controller", Modifier.PRIVATE, Modifier.FINAL)
                        .addMethod(
                                MethodSpec.constructorBuilder()
                                        .addModifiers(Modifier.PUBLIC)
                                        .addParameter(owner, "controller")
                                        .addStatement(
                                                "this.controller = $T.requireNonNull(controller)",
                                                Objects.class)
                                        .build());
        advice.addMethod(
                MethodSpec.methodBuilder("handle")
                        .addModifiers(Modifier.PUBLIC)
                        .returns(VIEW)
                        .addAnnotation(
                                AnnotationSpec.builder(annotation("ExceptionHandler"))
                                        .addMember("value", "$T.class", Exception.class)
                                        .build())
                        .addParameter(Exception.class, "error")
                        .addParameter(REQUEST, "request")
                        .addStatement(
                                "var handler ="
                                    + " request.getAttribute($T.BEST_MATCHING_HANDLER_ATTRIBUTE)",
                                ClassName.get("org.springframework.web.servlet", "HandlerMapping"))
                        .addStatement(
                                "String endpoint = handler instanceof $T method ?"
                                    + " method.getMethod().getName() : $S",
                                ClassName.get("org.springframework.web.method", "HandlerMethod"),
                                "request")
                        .addStatement(
                                "return controller.__failure(endpoint, $T.empty(), error, request)",
                                INPUTS)
                        .build());
        var files = new ArrayList<JavaFile>();
        files.add(file(pkg, type));
        files.add(file(pkg, advice));
        if (!plan.schemas().isEmpty())
            files.add(new DtoGenerator().generate(adapter.name(), pkg + ".dto", plan.schemas()));
        if (!plan.mappings().isEmpty())
            files.addAll(
                    new MappingGenerator()
                            .generate(
                                    adapter.name(),
                                    pkg + ".mapping",
                                    unit,
                                    project,
                                    plan.mappings()));
        return List.copyOf(files);
    }

    private MethodSpec entry(
            InboundHttpAdapterNode adapter, InboundHttpAdapterNode.Endpoint source) {
        var mapping =
                AnnotationSpec.builder(annotation("RequestMapping"))
                        .addMember(
                                "path", "$S", InboundResolver.join(adapter.base(), source.route()))
                        .addMember("method", "$T.$L", annotation("RequestMethod"), source.verb())
                        .addMember("produces", "$S", "text/html");
        if (source.bindings().stream().anyMatch(b -> b.kind().equals("form")))
            mapping.addMember("consumes", "$S", "application/x-www-form-urlencoded");
        var method =
                MethodSpec.methodBuilder(source.name())
                        .addModifiers(Modifier.PUBLIC)
                        .returns(VIEW)
                        .addAnnotation(mapping.build())
                        .addParameter(REQUEST, "request")
                        .addStatement("var inputs = $T.empty()", INPUTS)
                        .beginControlFlow("try");
        method.addStatement("inputs = $T.capture(request, $L)", INPUTS, bindings(source.bindings()))
                .addStatement("return __$N(inputs, request)", source.name())
                .nextControlFlow("catch ($T error)", Exception.class)
                .addStatement("return __failure($S, inputs, error, request)", source.name())
                .endControlFlow();
        return method.build();
    }

    private MethodSpec loader(ResolvedInbound.Endpoint endpoint, ClassName mappings) {
        var source = endpoint.source();
        var view = source.view().orElseThrow();
        var method =
                MethodSpec.methodBuilder("__" + source.name())
                        .addModifiers(Modifier.PRIVATE)
                        .returns(VIEW)
                        .addParameter(INPUTS, "inputs")
                        .addParameter(REQUEST, "request")
                        .addStatement("inputs.check()");
        Map<String, String> variables = new HashMap<>();
        int index = 0;
        for (var b : source.bindings()) {
            var scalar =
                    org.vernac.compiler.symbols.BuiltinTypes.find(b.type().name()).orElseThrow();
            var java = TypeName.get(scalar);
            variables.put(b.kind() + "." + b.name(), "__wire" + index);
            String key = b.kind() + "." + b.externalName();
            if (b.type().isOptional())
                method.addStatement(
                        "$T<$T> __wire$L = inputs.optional($S).map(value -> ($T) $T.parse($S,"
                            + " value))",
                        Optional.class,
                        java.box(),
                        index,
                        key,
                        java.box(),
                        ClassName.get("org.vernac.runtime.http.inbound", "WireValues"),
                        b.type().name());
            else
                method.addStatement(
                        "$T __wire$L = ($T) $T.parse($S, inputs.required($S, $L))",
                        java,
                        index,
                        java.box(),
                        ClassName.get("org.vernac.runtime.http.inbound", "WireValues"),
                        b.type().name(),
                        key,
                        b.defaultValue()
                                .map(s -> CodeBlock.of("$S", s))
                                .orElse(CodeBlock.of("null")));
            index++;
        }
        var arguments = new ArrayList<CodeBlock>();
        index = 0;
        var renderer = new MappingGenerator();
        for (var a : endpoint.arguments()) {
            if (a.source() == null) {
                arguments.add(CodeBlock.of("null"));
                continue;
            }
            CodeBlock input = InboundHttpGenerator.input(a.source(), variables);
            CodeBlock converted =
                    a.source().optional()
                            ? CodeBlock.of(
                                    "$L.map(value -> $L).orElse(null)",
                                    input,
                                    renderer.convert(
                                            a.conversion(),
                                            CodeBlock.of("value"),
                                            mappings,
                                            source.name(),
                                            CodeBlock.of("$S", a.target().name()),
                                            0))
                            : renderer.convert(
                                    a.conversion(),
                                    input,
                                    mappings,
                                    source.name(),
                                    CodeBlock.of("$S", a.target().name()),
                                    0);
            method.addStatement("var __arg$L = $L", index, converted);
            arguments.add(CodeBlock.of("__arg$L", index++));
        }
        var call =
                CodeBlock.of(
                        "this.$N.execute($L)",
                        endpoint.dependency().field().name(),
                        CodeBlock.join(arguments, ", "));
        boolean optional =
                endpoint.dependency()
                        .usecase()
                        .resultType()
                        .map(TypeNode::isOptional)
                        .orElse(false);
        if (endpoint.result() == null || view.redirect().isPresent() && !optional)
            method.addStatement("$L", call);
        else {
            method.addStatement("var __result = $L", call);
            if (optional)
                method.beginControlFlow("if (__result.isEmpty())")
                        .addStatement(
                                "return $T.absent($S, $L, inputs)",
                                RESPONSES,
                                view.absentView().orElseThrow(),
                                source.absentStatus().orElseThrow())
                        .endControlFlow();
        }
        if (view.redirect().isPresent())
            method.addStatement(
                    "return $T.redirect($S, $L, $L, request)",
                    RESPONSES,
                    view.redirect().get(),
                    source.verb().equals("POST"),
                    view.notice().map(s -> CodeBlock.of("$S", s)).orElse(CodeBlock.of("null")));
        else
            method.addStatement(
                    "return $T.view($S, $L, $L, $L, inputs)",
                    RESPONSES,
                    view.template(),
                    source.status(),
                    view.modelName().map(s -> CodeBlock.of("$S", s)).orElse(CodeBlock.of("null")),
                    endpoint.result() == null
                            ? CodeBlock.of("null")
                            : optional
                                    ? CodeBlock.of("__result.orElseThrow()")
                                    : CodeBlock.of("__result"));
        return method.build();
    }

    private MethodSpec failure(InboundHttpAdapterNode adapter, ResolvedProject project, String pkg) {
        var method =
                MethodSpec.methodBuilder("__failure")
                        .addModifiers(Modifier.PUBLIC)
                        .returns(VIEW)
                        .addParameter(String.class, "endpoint")
                        .addParameter(INPUTS, "inputs")
                        .addParameter(Exception.class, "error")
                        .addParameter(REQUEST, "request")
                        .beginControlFlow("try");
        for (var endpoint : adapter.endpoints())
            if (!endpoint.errorRules().isEmpty() || endpoint.errorImplementation().isPresent()) {
                method.beginControlFlow("if (endpoint.equals($S))", endpoint.name());
                rules(method, adapter, endpoint.errorRules(), project);
                endpoint.errorImplementation()
                        .ifPresent(
                                name ->
                                        method.addStatement(
                                                "return $T.error($S,"
                                                    + " $T.requireNonNull($L.handle(endpoint,"
                                                    + " error)), inputs, error)",
                                                RESPONSES,
                                                adapter.errorView().orElseThrow(),
                                                Objects.class,
                                                org.vernac.compiler.util.JavaImplementations.resolve(name,List.of(),pkg)));
                method.endControlFlow();
            }
        rules(method, adapter, adapter.errorRules(), project);
        if (adapter.errorImplementation().isPresent())
            method.addStatement(
                    "return $T.error($S, $T.requireNonNull($L.handle(endpoint, error)), inputs,"
                        + " error)",
                    RESPONSES,
                    adapter.errorView().orElseThrow(),
                    Objects.class,
                    org.vernac.compiler.util.JavaImplementations.resolve(adapter.errorImplementation().get(),List.of(),pkg));
        else
            method.addStatement(
                    "return $T.error($S, $T.defaultReply(error), inputs, error)",
                    RESPONSES,
                    adapter.errorView().orElseThrow(),
                    ERRORS);
        method.nextControlFlow("catch ($T policyFailure)", Exception.class)
                .addStatement(
                        "return $T.failure($S, inputs, policyFailure)",
                        RESPONSES,
                        adapter.errorView().orElseThrow())
                .endControlFlow();
        return method.build();
    }

    private void rules(
            MethodSpec.Builder method,
            InboundHttpAdapterNode adapter,
            List<InboundHttpAdapterNode.ErrorRule> rules,
            ResolvedProject project) {
        for (var rule : rules) {
            method.beginControlFlow("if ($L)", InboundErrorConditions.condition(rule, project));
            CodeBlock reply =
                    rule.code().isPresent()
                            ? CodeBlock.of(
                                    "new $T($L, $S, $S)",
                                    ERRORS.nestedClass("Reply"),
                                    rule.status(),
                                    rule.code().get(),
                                    rule.message().orElseThrow())
                            : CodeBlock.of("$T.withStatus(error, $L)", ERRORS, rule.status());
            var reload = rule.view().flatMap(InboundHttpAdapterNode.ErrorView::reload);
            if (reload.isPresent()) {
                var target =
                        adapter.endpoints().stream()
                                .filter(e -> e.name().equals(reload.get()))
                                .findFirst()
                                .orElseThrow();
                method.addStatement(
                        "return $T.redisplay(() -> __$N(inputs.forLoader($L), request), $L, inputs,"
                            + " $S, error)",
                        RESPONSES,
                        reload.get(),
                        bindings(target.bindings()),
                        reply,
                        adapter.errorView().orElseThrow());
            } else
                method.addStatement(
                        "return $T.error($S, $L, inputs, error)",
                        RESPONSES,
                        rule.view()
                                .flatMap(InboundHttpAdapterNode.ErrorView::template)
                                .orElse(adapter.errorView().orElseThrow()),
                        reply);
            method.endControlFlow();
        }
    }

    private CodeBlock bindings(List<InboundHttpAdapterNode.Binding> bindings) {
        return CodeBlock.of(
                "$T.of($L)",
                List.class,
                CodeBlock.join(
                        bindings.stream()
                                .map(
                                        b ->
                                                CodeBlock.of(
                                                        "new $T($S, $S, $S, $L)",
                                                        INPUTS.nestedClass("Binding"),
                                                        b.kind(),
                                                        b.name(),
                                                        b.externalName(),
                                                        b.sensitive()))
                                .toList(),
                        ", "));
    }

    private JavaFile file(String pkg, TypeSpec.Builder type) {
        return JavaFile.builder(pkg, type.build()).indent("    ").skipJavaLangImports(true).build();
    }
}
