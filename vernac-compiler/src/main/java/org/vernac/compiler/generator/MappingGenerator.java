package org.vernac.compiler.generator;

import com.palantir.javapoet.*;
import javax.lang.model.element.Modifier;
import java.util.*;
import org.jspecify.annotations.*;
import org.vernac.compiler.ast.*;
import org.vernac.compiler.pipeline.ResolvedProject;
import org.vernac.compiler.mapping.ResolvedMapping;
import org.vernac.runtime.ports.PatchField;
import static org.vernac.compiler.mapping.ResolvedMapping.*;

/** Renders a type-checked conversion plan; factories preserve domain validation. */
public final class MappingGenerator {
    private static final ClassName CHECKS=ClassName.get("org.vernac.runtime.json","MappingChecks");
    public List<JavaFile> generate(OutboundAdapterNode adapter,CompilationUnitNode unit,ResolvedProject project) {
        ClassName owner=ClassName.get(unit.namespace()+".adapter.outbound.mapping",adapter.name()+"Mappings");
        var holder=TypeSpec.classBuilder(owner).addModifiers(Modifier.PUBLIC,Modifier.FINAL).addAnnotation(NullMarked.class)
            .addJavadoc("Adapter-local conversions. Generated by Vernac; do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
        List<JavaFile> files=new ArrayList<>();
        for(var mapping:project.mappings().get(adapter)) {
            String label=unit.namespace()+"."+adapter.name()+"."+mapping.source().name();
            var method=MethodSpec.methodBuilder(mapping.source().name()).addModifiers(Modifier.PUBLIC,Modifier.STATIC)
                .returns(mapping.target().javaType()).addParameter(mapping.input().javaType(),"source")
                .addStatement("$T.requireNonNull(source, $S)",Objects.class,"Mapping source must not be null");
            if(mapping.source().javaBody().isPresent() || mapping.source().implementation().isPresent()) {
                ClassName companion=ClassName.get(owner.packageName(),"__VernacMapping_"+adapter.name()+"_"+mapping.source().name());
                var body=TypeSpec.classBuilder(companion).addModifiers(Modifier.FINAL).addAnnotation(NullMarked.class)
                    .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
                var bridge=MethodSpec.methodBuilder(mapping.source().name()).addModifiers(Modifier.STATIC)
                    .returns(mapping.target().javaType()).addParameter(mapping.input().javaType(),"source");
                if(mapping.source().implementation().isPresent()) bridge.addStatement("return $L.$N(source)",mapping.source().implementation().get(),mapping.source().name());
                else {
                    new BehaviorGenerator().addBodyImports(body,companion,mapping.source().javaImports(),unit,project,mapping.source().javaBody().orElseThrow());
                    bridge.addCode("$L\n",mapping.source().javaBody().orElseThrow());
                }
                body.addMethod(bridge.build());files.add(file(owner.packageName(),body));
                method.addStatement("return $T.result($S, $S, () -> $T.$N(source))",CHECKS,label,"$",companion,mapping.source().name());
            } else {
                List<CodeBlock> args=new ArrayList<>();int index=0;
                for(var assignment:mapping.assignments()) {
                    var f=assignment.target();TypeName type=f.type().javaType();
                    CodeBlock value;
                    if(assignment.path()==null) value=f.patch()?CodeBlock.of("$T.unchanged()",PatchField.class):CodeBlock.of("null");
                    else {
                        CodeBlock input=path(assignment.path());
                        CodeBlock converted;
                        if(assignment.path().patch() || assignment.path().optional()) {
                            converted=CodeBlock.of("$L.map(value -> $L)",input,convert(assignment.conversion(),CodeBlock.of("value"),owner,label,CodeBlock.of("$S","$."+f.name()),0));
                            if(!assignment.path().patch())converted=CodeBlock.of("$L.orElse(null)",converted);
                        } else converted=convert(assignment.conversion(),input,owner,label,CodeBlock.of("$S","$."+f.name()),0);
                        value=CodeBlock.of("$T.field($S, $S, () -> $L)",CHECKS,label,"$."+f.name(),converted);
                    }
                    if(f.patch())type=ParameterizedTypeName.get(ClassName.get(PatchField.class),type.box());
                    else if(f.optional())type=type.box().annotated(AnnotationSpec.builder(Nullable.class).build());
                    method.addStatement("$T __mapped$L = $L",type,index,value);args.add(CodeBlock.of("__mapped$L",index++));
                }
                method.addStatement("return $T.result($S, $S, () -> $T.of($L))",CHECKS,label,"$",mapping.target().javaType(),CodeBlock.join(args,", "));
            }
            holder.addMethod(method.build());
        }
        files.add(file(owner.packageName(),holder));return List.copyOf(files);
    }
    private CodeBlock path(Path path) {
        CodeBlock value=CodeBlock.of("source");boolean optional=false;int index=0;
        for(var field:path.fields()) {
            if(optional) value=CodeBlock.of("$L.$L(v$L -> v$L.$N())",value,field.optional()?"flatMap":"map",index,index,field.name());
            else value=CodeBlock.of("$L.$N()",value,field.name());
            optional|=field.optional() && !field.patch();index++;
        }
        return value;
    }
    private CodeBlock convert(Conversion conversion,CodeBlock value,ClassName owner,String label,CodeBlock path,int depth) {
        if(conversion instanceof Identity)return value;
        if(conversion instanceof Named n)return CodeBlock.of("$T.$N($L)",owner,n.name(),value);
        if(conversion instanceof Unwrap u)return convert(u.next(),CodeBlock.of("$L.$N()",value,u.field().name()),owner,label,path,depth);
        if(conversion instanceof Wrap w)return CodeBlock.of("$T.of($L)",w.target().javaType(),convert(w.next(),value,owner,label,path,depth));
        var e=(Elements)conversion;
        var nextPath=CodeBlock.of("$L + $S + index$L + $S",path,"[",depth,"]");
        CodeBlock result=CodeBlock.of("$T.elements($L, (element$L, index$L) -> $T.field($S, $L, () -> $L))",CHECKS,value,depth,depth,CHECKS,label,nextPath,
            convert(e.element(),CodeBlock.of("element$L",depth),owner,label,nextPath,depth+1));
        return e.target().symbol()==null?result:CodeBlock.of("$T.of($L)",e.target().javaType(),result);
    }
    private JavaFile file(String pkg,TypeSpec.Builder type) {return JavaFile.builder(pkg,type.build()).indent("    ").skipJavaLangImports(true).build();}
}
