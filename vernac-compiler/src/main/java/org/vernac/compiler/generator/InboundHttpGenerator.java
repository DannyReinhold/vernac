package org.vernac.compiler.generator;

import java.util.*;
import javax.lang.model.element.Modifier;
import com.palantir.javapoet.*;
import org.jspecify.annotations.*;
import org.vernac.compiler.ast.*;
import org.vernac.compiler.inbound.*;
import org.vernac.compiler.mapping.ResolvedMapping;
import org.vernac.compiler.pipeline.ResolvedProject;
import static org.vernac.compiler.mapping.ResolvedMapping.*;

/** Small Spring controllers; usecases own transactions and mappings own the ACL. */
public final class InboundHttpGenerator {
    private static ClassName spring(String name) {return ClassName.get("org.springframework.web.bind.annotation",name);}
    private static final ClassName RESPONSE=ClassName.get("org.springframework.http","ResponseEntity");
    private static final ClassName ERRORS=ClassName.get("org.vernac.runtime.http.inbound","InboundHttpErrors");
    private static final ClassName WIRE=ClassName.get("org.vernac.runtime.http.inbound","WireValues");
    public List<JavaFile> generate(InboundHttpAdapterNode adapter, CompilationUnitNode unit, ResolvedProject project, ResolvedInbound plan) {
        String pkg=unit.namespace()+".adapter.inbound.http";
        ClassName owner=ClassName.get(pkg,adapter.name());
        ClassName mappings=ClassName.get(pkg+".mapping",adapter.name()+"Mappings");
        var builder=TypeSpec.classBuilder(owner).addModifiers(Modifier.PUBLIC,Modifier.FINAL).addAnnotation(NullMarked.class)
                .addAnnotation(spring("RestController")).addJavadoc("HTTP inbound adapter generated by Vernac. Do not edit.\n");
        var ctor=MethodSpec.constructorBuilder().addModifiers(Modifier.PUBLIC);
        for(var dependency:plan.dependencies()) {
            ClassName type=ClassName.get(dependency.symbol().identity().namespace()+".usecase",dependency.symbol().identity().name());
            builder.addField(type,dependency.field().name(),Modifier.PRIVATE,Modifier.FINAL);
            ctor.addParameter(type,dependency.field().name()).addStatement("this.$N = $T.requireNonNull($N)",dependency.field().name(),Objects.class,dependency.field().name());
        }
        builder.addMethod(ctor.build());
        for(var endpoint:plan.endpoints())builder.addMethod(endpoint(adapter,endpoint,mappings));
        var advice=TypeSpec.classBuilder(adapter.name()+"Errors").addModifiers(Modifier.PUBLIC,Modifier.FINAL).addAnnotation(NullMarked.class)
                .addAnnotation(AnnotationSpec.builder(ClassName.get("org.springframework.core.annotation","Order")).addMember("value","0").build())
                .addAnnotation(AnnotationSpec.builder(spring("RestControllerAdvice")).addMember("assignableTypes","$T.class",owner).build());
        var handler=MethodSpec.methodBuilder("handle").addModifiers(Modifier.PUBLIC)
                .addAnnotation(AnnotationSpec.builder(spring("ExceptionHandler")).addMember("value","$T.class",Exception.class).build())
                .returns(ParameterizedTypeName.get(RESPONSE,ERRORS.nestedClass("Body"))).addParameter(Exception.class,"error");
        boolean policies = !adapter.errorRules().isEmpty() || adapter.errorImplementation().isPresent()
                || adapter.endpoints().stream().anyMatch(e -> !e.errorRules().isEmpty() || e.errorImplementation().isPresent());
        if (policies) {
            var policy = MethodSpec.methodBuilder("policy").addModifiers(Modifier.PRIVATE,Modifier.STATIC)
                .returns(ERRORS.nestedClass("Reply")).addParameter(String.class,"endpoint").addParameter(Exception.class,"error");
            for (var endpoint : adapter.endpoints()) {
                if (!endpoint.errorRules().isEmpty() || endpoint.errorImplementation().isPresent()) {
                    policy.beginControlFlow("if (endpoint.equals($S))",endpoint.name());
                    addRules(policy,endpoint.errorRules(),project);
                    endpoint.errorImplementation().ifPresent(n -> policy.addStatement("return $L.handle(endpoint, error)",n));
                    policy.endControlFlow();
                }
            }
            addRules(policy,adapter.errorRules(),project);
            if (adapter.errorImplementation().isPresent()) policy.addStatement("return $L.handle(endpoint, error)",adapter.errorImplementation().get());
            else policy.addStatement("return $T.defaultReply(error)",ERRORS);
            advice.addMethod(policy.build());
            handler.addStatement("return $T.respond(error, $L::policy)",ERRORS,adapter.name()+"Errors");
        } else handler.addStatement("return $T.respond(error)",ERRORS);
        advice.addMethod(handler.build());
        BehaviorGenerator.addDebugFingerprint(builder,file(pkg,builder),unit,project);
        var files=new ArrayList<JavaFile>();files.add(file(pkg,builder));files.add(file(pkg,advice));
        if(!plan.schemas().isEmpty())files.add(new DtoGenerator().generate(adapter.name(),pkg+".dto",plan.schemas()));
        if(!plan.mappings().isEmpty())files.addAll(new MappingGenerator().generate(adapter.name(),pkg+".mapping",unit,project,plan.mappings()));
        return List.copyOf(files);
    }
    private void addRules(MethodSpec.Builder method,List<InboundHttpAdapterNode.ErrorRule> rules,ResolvedProject project) {
        for (var rule : rules) {
            CodeBlock condition;
            if (rule.selector().equals("rejection")) {
                var type=(org.vernac.compiler.symbols.ResolvedType.Declared)project.typeOf(rule.rejectionType().orElseThrow());
                var id=type.symbol().identity();
                condition=CodeBlock.of("$T.rejection(error, $T.$L)",ERRORS,ClassName.get(id.namespace()+".domain",id.name()),rule.constant());
            } else if (rule.selector().equals("integration")) {
                condition=CodeBlock.of("$T.integration(error, $S, $T.$L)",ERRORS,rule.responsibility(),
                    ClassName.get("org.vernac.runtime.ports","IntegrationCategory"),rule.category());
            } else condition=CodeBlock.of("$T.matches(error, $S)",ERRORS,rule.selector());
            method.beginControlFlow("if ($L)",condition);
            if (rule.code().isPresent()) method.addStatement("return new $T($L, $S, $S)",ERRORS.nestedClass("Reply"),rule.status(),rule.code().get(),rule.message().orElseThrow());
            else method.addStatement("return $T.withStatus(error, $L)",ERRORS,rule.status());
            method.endControlFlow();
        }
    }
    private MethodSpec endpoint(InboundHttpAdapterNode adapter,ResolvedInbound.Endpoint endpoint,ClassName mappings) {
        var source=endpoint.source();
        var mapping=AnnotationSpec.builder(spring("RequestMapping"))
                .addMember("path","$S",InboundResolver.join(adapter.base(),source.route()))
                .addMember("method","$T.$L",spring("RequestMethod"),source.verb());
        if(source.bodyType().isPresent())mapping.addMember("consumes","$S","application/json");
        if(source.responseType().isPresent())mapping.addMember("produces","$S","application/json");
        var method=MethodSpec.methodBuilder(source.name()).addModifiers(Modifier.PUBLIC)
                .returns(ParameterizedTypeName.get(RESPONSE,WildcardTypeName.subtypeOf(Object.class)))
                .addAnnotation(mapping.build());
        Map<String,String> variables=new HashMap<>();int index=0;
        for(var binding:source.bindings()) {
            String name="__wire"+index;variables.put(binding.kind()+"."+binding.name(),name);
            var annotation=AnnotationSpec.builder(spring(switch(binding.kind()){case "path"->"PathVariable";case "query"->"RequestParam";default->"RequestHeader";}))
                    .addMember("name","$S",binding.externalName());
            if(binding.type().isOptional())annotation.addMember("required","false");
            var parameter=ParameterSpec.builder(String.class,"__raw"+index).addAnnotation(annotation.build());
            if(binding.type().isOptional())parameter.addAnnotation(Nullable.class);
            method.addParameter(parameter.build());index++;
        }
        if(source.bodyType().isPresent()) {
            ClassName body=ClassName.get(mappings.packageName().replace(".mapping",".dto"),adapter.name()+"Dtos",source.bodyType().get().name());
            method.addParameter(ParameterSpec.builder(body,"__body").addAnnotation(spring("RequestBody")).build());
        }
        method.beginControlFlow("try");index=0;
        for(var binding:source.bindings()) {
            Class<?> type=org.vernac.compiler.symbols.BuiltinTypes.find(binding.type().name()).orElseThrow();
            TypeName raw=TypeName.get(type);
            CodeBlock parsed=CodeBlock.of("($T) $T.parse($S, __raw$L)",raw.box(),WIRE,binding.type().name(),index);
            if(binding.type().isOptional())method.addStatement("$T<$T> __wire$L = $T.ofNullable(__raw$L).map(value -> ($T) $T.parse($S, value))",Optional.class,raw.box(),index,Optional.class,index,raw.box(),WIRE,binding.type().name());
            else method.addStatement("$T __wire$L = $L",raw,index,parsed);
            index++;
        }
        var renderer=new MappingGenerator();var args=new ArrayList<CodeBlock>();index=0;
        for(var argument:endpoint.arguments()) {
            if(argument.source()==null) {args.add(CodeBlock.of("null"));continue;}
            CodeBlock input=input(argument.source(),variables);
            CodeBlock converted=argument.source().optional()
                    ? CodeBlock.of("$L.map(value -> $L).orElse(null)",input,renderer.convert(argument.conversion(),CodeBlock.of("value"),mappings,source.name(),CodeBlock.of("$S",argument.target().name()),0))
                    : renderer.convert(argument.conversion(),input,mappings,source.name(),CodeBlock.of("$S",argument.target().name()),0);
            // var keeps exact conversion types, including named mapping and collection results.
            method.addStatement("var __arg$L = $L",index,converted);args.add(CodeBlock.of("__arg$L",index++));
        }
        CodeBlock invocation=CodeBlock.of("this.$N.execute($L)",endpoint.dependency().field().name(),CodeBlock.join(args,", "));
        if(endpoint.result()==null) {
            method.addStatement("$L",invocation).addStatement("return $T.status($L).build()",RESPONSE,source.status());
        } else {
            method.addStatement("var __result = $L",invocation);
            boolean optional=endpoint.dependency().usecase().resultType().map(TypeNode::isOptional).orElse(false);
            if(optional)method.beginControlFlow("if (__result.isEmpty())").addStatement("return $T.status($L).build()",RESPONSE,source.absentStatus().orElseThrow()).endControlFlow();
            method.beginControlFlow("try").addStatement("return $T.status($L).body($T.$N($L))",RESPONSE,source.status(),mappings,
                    endpoint.response().source().name(),optional?CodeBlock.of("__result.orElseThrow()"):CodeBlock.of("__result"))
                    .nextControlFlow("catch ($T error)",Exception.class).addStatement("throw $T.response($S, error)",ERRORS,source.name()).endControlFlow();
        }
        method.nextControlFlow("catch ($T error)",Exception.class).addStatement("throw $T.invocation($S, error)",ERRORS,source.name()).endControlFlow();
        return method.build();
    }
    private CodeBlock input(Path path,Map<String,String> variables) {
        var fields=path.fields();String group=fields.getFirst().name();CodeBlock value;boolean optional=false;int start;
        if(group.equals("body")) {value=CodeBlock.of("__body");start=1;}
        else {value=CodeBlock.of("$L",variables.get(group+"."+fields.get(1).name()));optional=fields.get(1).optional();start=2;}
        for(int i=start;i<fields.size();i++) {
            var field=fields.get(i);
            if(optional)value=CodeBlock.of("$L.$L(v$L -> v$L.$N())",value,field.optional()?"flatMap":"map",i,i,field.name());
            else value=CodeBlock.of("$L.$N()",value,field.name());
            optional|=field.optional();
        }
        return value;
    }
    private JavaFile file(String pkg,TypeSpec.Builder type) {return JavaFile.builder(pkg,type.build()).indent("    ").skipJavaLangImports(true).build();}
}
