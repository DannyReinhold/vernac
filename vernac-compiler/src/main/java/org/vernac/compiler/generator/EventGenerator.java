package org.vernac.compiler.generator;
import com.palantir.javapoet.*;
import java.time.Instant;
import java.util.*;
import javax.lang.model.element.Modifier;
import org.jspecify.annotations.*;
import org.vernac.compiler.ast.*;
import org.vernac.compiler.pipeline.*;
import org.vernac.runtime.*;

public final class EventGenerator {
    public List<JavaFile> generate(EventNode event, CompilationUnitNode unit, ResolvedProject project) {
        ClassName owner = ClassName.get(unit.namespace()+".domain",event.name());
        var type = TypeSpec.classBuilder(owner).addModifiers(Modifier.PUBLIC,Modifier.FINAL).addAnnotation(NullMarked.class).addSuperinterface(DomainEvent.class)
                .addJavadoc("Domain event generated by Vernac. Do not edit.\n");
        // Metadata uses runtime types directly; payload types always come from semantic resolution.
        type.addField(EventId.class,"eventId",Modifier.PRIVATE,Modifier.FINAL).addField(Instant.class,"occurredAt",Modifier.PRIVATE,Modifier.FINAL);
        var ctor = MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).addParameter(EventId.class,"eventId").addParameter(Instant.class,"occurredAt")
            .addStatement("this.eventId = $T.requireNonNull(eventId, $S)",DomainChecks.class,"eventId")
            .addStatement("this.occurredAt = $T.requireNonNull(occurredAt, $S)",DomainChecks.class,"occurredAt");
        var create = MethodSpec.methodBuilder("create").addModifiers(Modifier.PUBLIC,Modifier.STATIC).returns(owner);
        var restore = MethodSpec.methodBuilder("reconstitute").addModifiers(Modifier.PUBLIC,Modifier.STATIC).returns(owner).addParameter(EventId.class,"eventId").addParameter(Instant.class,"occurredAt");
        var readName = ClassName.get(owner.packageName()+".access",event.name()+"Read");
        var read = TypeSpec.interfaceBuilder(readName).addModifiers(Modifier.PUBLIC).addAnnotation(NullMarked.class);
        var view = TypeSpec.classBuilder("__ReadView").addModifiers(Modifier.PRIVATE,Modifier.FINAL).addSuperinterface(readName);
        for (var name : List.of("eventId","occurredAt")) {
            TypeName t = ClassName.get(name.equals("eventId")?EventId.class:Instant.class);
            type.addMethod(MethodSpec.methodBuilder(name).addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(t).addStatement("return this.$N",name).build());
            read.addMethod(MethodSpec.methodBuilder(name).addModifiers(Modifier.PUBLIC,Modifier.ABSTRACT).returns(t).build());
            view.addMethod(MethodSpec.methodBuilder(name).addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(t).addStatement("return $L.this.$N()",owner.simpleName(),name).build());
        }
        List<String> args = new ArrayList<>();
        for(var f:event.fields()) {
            TypeName raw=ResolvedJavaTypes.javaType(project.typeOf(f.type()));
            TypeName input=f.type().isOptional()?raw.annotated(AnnotationSpec.builder(Nullable.class).build()):raw;
            TypeName result=f.type().isOptional()?ParameterizedTypeName.get(ClassName.get(Optional.class),raw):raw;
            type.addField(input,f.name(),Modifier.PRIVATE,Modifier.FINAL);
            ctor.addParameter(input,f.name());create.addParameter(input,f.name());restore.addParameter(input,f.name());args.add(f.name());
            if(f.type().isOptional()) ctor.addStatement("this.$N = $N",f.name(),f.name());
            else ctor.addStatement("this.$N = $T.requireNonNull($N, $S)",f.name(),DomainChecks.class,f.name(),event.name()+"."+f.name());
            var getter=MethodSpec.methodBuilder(f.name()).addModifiers(Modifier.PUBLIC).returns(result);
            if(f.type().isOptional()) getter.addStatement("return $T.ofNullable(this.$N)",Optional.class,f.name());else getter.addStatement("return this.$N",f.name());
            type.addMethod(getter.build());
            read.addMethod(MethodSpec.methodBuilder(f.name()).addModifiers(Modifier.PUBLIC,Modifier.ABSTRACT).returns(result).build());
            view.addMethod(MethodSpec.methodBuilder(f.name()).addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(result).addStatement("return $L.this.$N()",owner.simpleName(),f.name()).build());
        }
        String tail=args.isEmpty()?"":", "+String.join(", ",args);
        create.addStatement("return new $T($T.create(), $T.now()$L)",owner,EventId.class,Instant.class,tail);
        restore.addStatement("return new $T(eventId, occurredAt$L)",owner,tail);
        if(event.fields().stream().anyMatch(f->f.type().isOptional())) {
            var required=MethodSpec.methodBuilder("create").addModifiers(Modifier.PUBLIC,Modifier.STATIC).returns(owner);
            List<String> values=new ArrayList<>();
            for(var f:event.fields()) { if(!f.type().isOptional()) required.addParameter(ResolvedJavaTypes.javaType(project.typeOf(f.type())),f.name());values.add(f.type().isOptional()?"null":f.name()); }
            required.addStatement("return create($L)",String.join(", ",values));type.addMethod(required.build());
        }
        List<JavaFile> files=new ArrayList<>();
        if(!event.validations().isEmpty()) {
            ctor.addStatement("$T.validate(new __ReadView())",ValidationGenerator.companion(owner));type.addType(view.build());
            files.add(JavaFile.builder(readName.packageName(),read.build()).build());
            new ValidationGenerator().generate(owner,event.validations(),List.of(),unit,project).ifPresent(files::add);
        }
        type.addMethod(ctor.build()).addMethod(create.build()).addMethod(restore.build());
        type.addMethod(MethodSpec.methodBuilder("equals").addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(boolean.class)
            .addParameter(ClassName.get(Object.class).annotated(AnnotationSpec.builder(Nullable.class).build()),"other")
            .addStatement("return other instanceof $T that && eventId.equals(that.eventId)",owner).build());
        type.addMethod(MethodSpec.methodBuilder("hashCode").addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(int.class).addStatement("return eventId.hashCode()").build());
        String expression="\""+event.name()+"[eventId=\" + eventId + \", occurredAt=\" + occurredAt";
        for(var f:event.fields()) expression+=" + \", "+f.name()+"=\" + "+f.name();
        type.addMethod(MethodSpec.methodBuilder("toString").addModifiers(Modifier.PUBLIC).addAnnotation(Override.class).returns(String.class).addStatement("return $L + $S",expression,"]").build());
        files.add(JavaFile.builder(owner.packageName(),type.build()).indent("    ").build());return files;
    }
}
