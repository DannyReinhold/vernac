package org.vernac.intellij;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import org.vernac.compiler.persistence.*;
import org.vernac.compiler.pipeline.*;

/** Reuses the independently tested consumer source; schema hashes are generated for the chosen namespace. */
final class VernacSaasTemplate {
    private static final String BASE="/projectTemplates/vernac-saas/";
    static void copyTo(Path directory,String name,String group,String artifact,String namespace,String version) throws IOException {
        Path root=directory.toAbsolutePath().normalize();
        Map<Path,byte[]> files=new LinkedHashMap<>();
        for(String relative:resource("/projectTemplates/vernac-saas-files.txt").lines().toList()) {
            if(relative.isBlank() || relative.startsWith("src/main/vernac-schema/")
                    || relative.endsWith("V20261116010000000__initial_documents.sql"))continue;
            String path=relative.replace("example/documentworkspace",namespace.replace('.','/'));
            String text=resource(BASE+relative).replace("example.documentworkspace",namespace)
                    .replace("example/documentworkspace",namespace.replace('.','/'))
                    .replace("saas-document-workspace",artifact);
            if(relative.equals("pom.xml"))text=text.replace("<groupId>example.saas</groupId>","<groupId>"+group+"</groupId>")
                    .replace("<vernac.version>0.6.0-SNAPSHOT</vernac.version>","<vernac.version>"+version+"</vernac.version>");
            if(relative.equals("README.md"))text="# "+VernacProjectTemplate.escapeMarkdown(name)+"\n\n"
                    +"Independent SaaS application generated by Vernac "+version+".\n\n"
                    +"Use JDK 21+, Python 3 and Docker Compose. Run `./mvnw package`, then `python3 run-local.py`.\n"
                    +"SNAPSHOT dependencies require the matching Vernac producer artifacts installed first.\n\n"
                    +text.substring(text.indexOf("The launcher persists"));
            Path destination=root.resolve(path).normalize();
            if(!destination.startsWith(root) || files.putIfAbsent(destination,text.getBytes(StandardCharsets.UTF_8))!=null)
                throw new IOException("Invalid SaaS template destination");
        }
        Path sourceRoot=root.resolve("src/main/vernac");
        Path model=sourceRoot.resolve(namespace.replace('.','/')).resolve("model.vernac");
        try {
            var unit=new VernacSourceParser().parse(model.toString(),new String(files.get(model),StandardCharsets.UTF_8));
            var index=new VernacProjectLoader().index(sourceRoot,List.of(new VernacSourceFile(model,unit)));
            var resolved=new ProjectTypeResolver().resolve(index);
            var empty=SchemaModel.empty();
            var schema=new SchemaBuilder(resolved,empty,Map.of(),new SchemaBuilder.Options(false,false)).build();
            var plan=new MigrationPlanner().plan(empty,schema,MigrationPlanner.Options.safe());
            String migration="V20261116010000000__initial_documents";
            files.put(root.resolve("src/main/resources/db/migration/"+migration+".sql"),plan.sql().getBytes(StandardCharsets.UTF_8));
            var snapshot=new SchemaHistory.Snapshot(1,migration+".sql",empty.fingerprint(),schema.fingerprint(),schema);
            files.put(root.resolve("src/main/vernac-schema/history/"+migration+".json"),
                    (SchemaModel.JSON.writeValueAsString(snapshot)+"\n").getBytes(StandardCharsets.UTF_8));
        } catch(RuntimeException invalid) {throw new IOException("Could not prepare SaaS namespace schema",invalid);}
        for(Path path:files.keySet())if(Files.exists(path,LinkOption.NOFOLLOW_LINKS))throw new IOException("Project file already exists: "+path);
        VernacProjectTemplate.writePrepared(root,files);
    }
    private static String resource(String name)throws IOException {
        try(var stream=VernacSaasTemplate.class.getResourceAsStream(name)) {
            if(stream==null)throw new IOException("Bundled SaaS template is incomplete: "+name);
            return new String(stream.readAllBytes(),StandardCharsets.UTF_8);
        }
    }
}
